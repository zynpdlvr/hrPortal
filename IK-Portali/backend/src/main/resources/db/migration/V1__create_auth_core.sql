
-- D0 / Kalıcı authentication veri modeli
-- ER V3.1: Role + User
-- UserRole kullanılmaz.

CREATE TABLE role (
                      role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      code VARCHAR(50) NOT NULL UNIQUE,
                      name VARCHAR(100) NOT NULL,
                      is_active BOOLEAN NOT NULL
);

CREATE TABLE app_user (
                          user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          public_id UUID NOT NULL
                                                          DEFAULT gen_random_uuid() UNIQUE,

                          role_id BIGINT NOT NULL
                              REFERENCES role(role_id),

                          login_email VARCHAR(254) NOT NULL UNIQUE,
                          password_hash VARCHAR(255) NOT NULL,
                          must_change_password BOOLEAN NOT NULL,
                          account_status VARCHAR(20) NOT NULL,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                          CONSTRAINT chk_app_user_status CHECK (
                              account_status IN (
                                                 'PENDING',
                                                 'ACTIVE',
                                                 'LOCKED',
                                                 'DISABLED'
                                  )
                              )
);

CREATE UNIQUE INDEX uq_app_user_email_lower
    ON app_user (LOWER(login_email));

